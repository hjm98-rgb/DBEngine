// ---- PNG 解码（仅 8bit RGB/RGBA，用于材质包贴图加载） ----
namespace {
inline int paeth(int a, int b, int c) {
    int p = a + b - c, pa = std::abs(p-a), pb = std::abs(p-b), pc = std::abs(p-c);
    if (pa <= pb && pa <= pc) return a;
    return pb <= pc ? b : c;
}
} // namespace

bool dbg::load_png(const char* path, int& w, int& h, std::vector<uint32_t>& rgba) {
    FILE* f = fopen(path, "rb");
    if (!f) return false;
    uint8_t sig[8];
    if (fread(sig,1,8,f) != 8 || sig[0]!=0x89||sig[1]!=0x50||sig[2]!=0x4E||sig[3]!=0x47||
        sig[4]!=0x0D||sig[5]!=0x0A||sig[6]!=0x1A||sig[7]!=0x0A) { fclose(f); return false; }
    int bitdepth=0, colortype=0;
    std::vector<uint8_t> idat;
    bool ihdr=false;
    for (;;) {
        uint8_t lenb[4]; if (fread(lenb,1,4,f)!=4) { fclose(f); return false; }
        uint32_t len = ((uint32_t)lenb[0]<<24)|((uint32_t)lenb[1]<<16)|((uint32_t)lenb[2]<<8)|lenb[3];
        char type[5]={0}; if (fread(type,1,4,f)!=4) { fclose(f); return false; }
        std::vector<uint8_t> data(len);
        if (len && fread(data.data(),1,len,f)!=len) { fclose(f); return false; }
        uint8_t crcb[4]; if (fread(crcb,1,4,f)!=4) { fclose(f); return false; }
        std::string t(type,4);
        if (t=="IHDR") {
            if (len<13) { fclose(f); return false; }
            w = ((uint32_t)data[0]<<24)|((uint32_t)data[1]<<16)|((uint32_t)data[2]<<8)|data[3];
            h = ((uint32_t)data[4]<<24)|((uint32_t)data[5]<<16)|((uint32_t)data[6]<<8)|data[7];
            bitdepth = data[8]; colortype = data[9];
            if (bitdepth != 8 || (colortype!=2 && colortype!=6)) { fclose(f); return false; }
            ihdr=true;
        } else if (t=="IDAT") {
            idat.insert(idat.end(), data.begin(), data.end());
        } else if (t=="IEND") {
            break;
        }
    }
    if (!ihdr) { fclose(f); return false; }
    fclose(f);
    int ch = (colortype==6)?4:3;
    size_t stride = (size_t)w*ch;
    size_t expect = (size_t)h*stride + h;
    std::vector<uint8_t> raw(expect);
    uLongf outlen = raw.size();
    if (uncompress(raw.data(), &outlen, idat.data(), idat.size()) != Z_OK) return false;
    rgba.assign((size_t)w*h, 0xff000000);
    size_t pos = 0;
    std::vector<uint8_t> prev(stride, 0), cur(stride);
    for (int y = 0; y < h; y++) {
        if (pos >= raw.size()) return false;
        uint8_t filter = raw[pos++];
        if (pos + stride > raw.size()) return false;
        const uint8_t* line = &raw[pos];
        for (size_t i = 0; i < stride; i++) {
            uint8_t x = line[i];
            uint8_t a = (i >= (size_t)ch) ? cur[i-ch] : 0;
            uint8_t b = prev[i];
            uint8_t c = (i >= (size_t)ch) ? prev[i-ch] : 0;
            switch (filter) {
                case 0: cur[i]=x; break;
                case 1: cur[i]=x+a; break;
                case 2: cur[i]=x+b; break;
                case 3: cur[i]=x+((a+b)>>1); break;
                case 4: cur[i]=x+paeth(a,b,c); break;
                default: return false;
            }
        }
        pos += stride;
        for (int x = 0; x < w; x++) {
            uint32_t r = cur[(size_t)x*ch], g = cur[(size_t)x*ch+1], b = cur[(size_t)x*ch+2];
            uint32_t a = (ch==4)?cur[(size_t)x*ch+3]:255;
            rgba[(size_t)y*w + x] = (a<<24)|(b<<16)|(g<<8)|r;
        }
        prev.swap(cur);
    }
    return true;
}
