// ---- 简易 PNG 输出（zlib 压缩，用于本机截图验证） ----
namespace {
uint32_t crc_table[256];
bool crc_init = false;
void init_crc() {
    for (uint32_t n = 0; n < 256; n++) {
        uint32_t c = n;
        for (int k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320u ^ (c >> 1)) : (c >> 1);
        crc_table[n] = c;
    }
    crc_init = true;
}
uint32_t crc32(const uint8_t* buf, size_t len) {
    if (!crc_init) init_crc();
    uint32_t c = 0xFFFFFFFFu;
    for (size_t i = 0; i < len; i++) c = crc_table[(c ^ buf[i]) & 0xFF] ^ (c >> 8);
    return c ^ 0xFFFFFFFFu;
}
void put_u32(FILE* f, uint32_t v) { fputc((v>>24)&255, f); fputc((v>>16)&255, f); fputc((v>>8)&255, f); fputc(v&255, f); }
void chunk(FILE* f, const char* type, const uint8_t* data, size_t len) {
    put_u32(f, (uint32_t)len);
    fwrite(type, 1, 4, f);
    if (len) fwrite(data, 1, len, f);
    std::vector<uint8_t> crcbuf(type, type+4);
    crcbuf.insert(crcbuf.end(), data, data+len);
    put_u32(f, crc32(crcbuf.data(), crcbuf.size()));
}
} // namespace

bool save_png(const Framebuffer& fb, const char* path) {
    FILE* f = fopen(path, "wb");
    if (!f) return false;
    static const uint8_t sig[8] = {0x89,0x50,0x4E,0x47,0x0D,0x0A,0x1A,0x0A};
    fwrite(sig, 1, 8, f);
    // IHDR
    uint8_t ihdr[13];
    uint32_t w = (uint32_t)fb.w, h = (uint32_t)fb.h;
    ihdr[0]=(w>>24)&255; ihdr[1]=(w>>16)&255; ihdr[2]=(w>>8)&255; ihdr[3]=w&255;
    ihdr[4]=(h>>24)&255; ihdr[5]=(h>>16)&255; ihdr[6]=(h>>8)&255; ihdr[7]=h&255;
    ihdr[8]=8; ihdr[9]=2; ihdr[10]=0; ihdr[11]=0; ihdr[12]=0;
    chunk(f, "IHDR", ihdr, 13);
    // IDAT: 每行前加 filter=0，像素按 RGB（跳过 alpha）
    std::vector<uint8_t> raw;
    raw.reserve((size_t)fb.w * 3 * (size_t)fb.h + (size_t)fb.h);
    for (int y = 0; y < fb.h; y++) {
        raw.push_back(0);
        for (int x = 0; x < fb.w; x++) {
            uint32_t c = fb.px[(size_t)y*fb.w + x];
            raw.push_back(c & 255);       // R（内存字节序 byte0=R）
            raw.push_back((c>>8)&255);    // G
            raw.push_back((c>>16)&255);   // B
        }
    }
    uLongf zlen = compressBound(raw.size());
    std::vector<uint8_t> zbuf(zlen);
    compress2(zbuf.data(), &zlen, raw.data(), raw.size(), 6);
    chunk(f, "IDAT", zbuf.data(), zlen);
    chunk(f, "IEND", nullptr, 0);
    fclose(f);
    return true;
}

